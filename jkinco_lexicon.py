# 收尾叮嘱。上下文增强不只是词表,还能给模型一句要求 —— 人名、单位、日期、数字
# 错了,纪要的事实就错了,而这几类恰恰是模型最爱「顺手改通顺」的地方。
CONTEXT_INSTRUCTION = "准确保留人名、单位名称、日期与数字，不要改写专业术语。"


def extra_terms() -> tuple[str, ...]:
    """部署方自己补充的术语。

    每个项目都有自己的专有名词:标段名、甲方单位、供应商、常出现的人名。
    这些词库里不可能预置,但恰恰是最容易被听错、错了最刺眼的 —— 留一个口子,
    用顿号或逗号分隔即可。
    """
    raw = os.getenv("JKINCO_ASR_EXTRA_TERMS", "")
    parts = raw.replace("，", "、").replace(",", "、").replace(" ", "、").split("、")
    seen: dict[str, None] = {}
    for part in parts:
        term = part.strip()
        if term:
            seen.setdefault(term, None)
    return tuple(seen)


def terms_for(app_mode: str = "auto") -> tuple[str, ...]:
    """某个场景该偏置的术语,按优先级排序。

    顺序即优先级:部署方补充的排最前(它们最专有),然后是平台名与本场景术语。
    auto/未知场景使用跨场景中性词表；general 不加任何业务场景词。分类前单边
    偏置工程词会形成「先偏出工程词、再据此判工程」的自我强化。
    """
    scene = str(app_mode or "").strip()
    scene_terms = _SCENE_TERMS.get(scene, AUTO_TERMS)
    ordered: dict[str, None] = {}
    for term in extra_terms() + PLATFORM_TERMS + scene_terms:
        ordered.setdefault(term, None)
    return tuple(ordered)


# 识别后的领域纠错。热词偏置能减少错误但消不掉,而有些错法是**固定**的 ——
# 「监理单位」听成「经理单位」,一份纪要里往往整篇都错。
#
# 收录标准只有一条:**错误形式在中文里根本不成词**。这样替换才不可能误伤。
# 明确排除掉的(留在这里是为了别人不要再把它们加回去):
#   经理例会  —— 合法,经理们开的会
#   浇注      —— 合法,冶金与铸造里就是这个词
#   隐蔽验收  —— 合法,是「隐蔽工程验收」的通行简称
# 这三个都是同音/近义陷阱,但它们各自都能独立成立,替换会改坏正确的句子。
DOMAIN_CORRECTIONS: tuple[tuple[str, str], ...] = (
    ("经理单位", "监理单位"),
    ("总经理工程师", "总监理工程师"),
    ("专业经理工程师", "专业监理工程师"),
    ("经理通知单", "监理通知单"),
    ("经理项目部", "监理项目部"),
    ("旁占", "旁站"),
    ("检验坯", "检验批"),
    ("塌落度", "坍落度"),
    ("五邻边", "五临边"),
    ("混泥土", "混凝土"),
    ("危大公程", "危大工程"),
    ("见证取洋", "见证取样"),
    ("平行捡验", "平行检验"),
)


def correct_domain_terms(text: str) -> str:
    """把固定错法改回来。

    只做字面替换,不做同音推断 —— 后者需要上下文判断,而判断错了就是在正确的
    纪要里制造错误。宁可漏掉一些,也不要改坏一句对的。
    """
    corrected = str(text or "")
    for wrong, right in DOMAIN_CORRECTIONS:
        if wrong in corrected:
            corrected = corrected.replace(wrong, right)
    return corrected
